#!/bin/bash

echo "====================================="
echo "  VestaScan Pro - Отправка на GitHub"
echo "====================================="

# Добавляем все изменения
git add .

# Спрашиваем комментарий
echo "Введите описание изменений (или нажмите Enter для авто-даты):"
read msg

if [ -z "$msg" ]; then
  msg="Автоматическое сохранение $(date '+%Y-%m-%d %H:%M:%S')"
fi

# Коммитим
git commit -m "$msg"

# Отправляем в ветку main (или master)
git push origin main || git push origin master

echo "====================================="
echo "  Готово! Код отправлен в репозиторий."
echo "====================================="